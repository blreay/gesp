// ===================== 组卷 =====================
function buildExam(srcPath, fills, meta) {
  const src = JSON.parse(fs.readFileSync(srcPath, 'utf8'));
  if (fills.length !== 50) throw new Error(meta.id + ': 填空题数量应为 50，实际 ' + fills.length);
  const progSec = src.sections.find(s => s.question_type === 'programming');
  if (!progSec) throw new Error(meta.id + ': 源卷缺少编程题部分');
  const questions = fills.map((f, i) => ({
    id: 'f' + (i + 1),
    type: 'fill',
    knowledge: f.kn,
    stem: f.stem,
    answer: f.ans,
    explanation: f.exp
  }));
  return {
    schema_version: 1,
    exam: {
      id: meta.id,
      title: meta.title,
      subtitle: meta.subtitle,
      total_score: 100,
      tags: meta.tags,
      prog_brief: src.exam.prog_brief
    },
    sections: [
      {
        title: '一、填空题（每题 1 分，共 50 分）',
        question_type: 'fill',
        score_per_question: 1,
        questions
      },
      {
        title: '二、编程题（每题 ' + progSec.score_per_question + ' 分，共 ' + (progSec.score_per_question * progSec.questions.length) + ' 分）',
        question_type: 'programming',
        score_per_question: progSec.score_per_question,
        questions: progSec.questions
      }
    ]
  };
}

